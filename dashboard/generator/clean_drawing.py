"""Prepare the Danfoss A266 drawing saved from Leanheat Monitor for the generator.

    python clean_drawing.py A266.1a.svg ../drawings/a266.svg [--config ../config.local.yaml]

Removes the draw.io "do not edit" comment and the value fields with their placeholders (--,-- °C,
(--,--) °C, the 1970 controller time), because Home Assistant draws live values there. Names the two
circuits (config circuit_titles, default "Space heating" / "Domestic hot water").
"""
from __future__ import annotations

import argparse
import re
from pathlib import Path

PLACEHOLDERS = ("--,-- °C", "(--,--) °C", "1st Jan 1970, 00:00")
DEFAULT_TITLES = ("Space heating", "Domestic hot water")


def clean(svg: str, titles: tuple[str, str] = DEFAULT_TITLES) -> str:
    svg = svg.replace("<!-- Do not edit this file with editors other than draw.io -->", "", 1)
    # live value fields: the generator draws these as Home Assistant labels
    svg = re.sub(r'<g [^>]*data-type="(?:ref_)?value"[^>]*><text[^>]*>[^<]*</text></g>', "", svg)
    for text in PLACEHOLDERS:
        svg = svg.replace(f">{text}<", "><")
    for title in titles:
        svg = svg.replace(">Circuit description<", f">{title}<", 1)
    return svg


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("src", type=Path, help="SVG saved from Leanheat Monitor")
    parser.add_argument("dst", type=Path, help="cleaned SVG, e.g. ../drawings/a266.svg")
    parser.add_argument("--config", type=Path, help="config with optional circuit_titles: [circuit 1, circuit 2]")
    args = parser.parse_args()
    titles = DEFAULT_TITLES
    if args.config:
        import yaml
        cfg = yaml.safe_load(args.config.read_text(encoding="utf-8")) or {}
        titles = tuple(cfg.get("circuit_titles") or DEFAULT_TITLES)
    out = clean(args.src.read_text(encoding="utf-8"), titles)
    args.dst.parent.mkdir(parents=True, exist_ok=True)
    args.dst.write_text(out, encoding="utf-8")
    left = len(re.findall(r">\(?--,--\)? °C<|>Circuit description<", out))
    print(f"wrote {args.dst} (placeholders left: {left})")


if __name__ == "__main__":
    main()
